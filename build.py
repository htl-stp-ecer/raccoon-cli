#!/usr/bin/env python3
"""build.py — build the raccoon-cli wheel (with the web IDE) inside Docker.

Nothing is installed on the host and nothing is written outside ./builds/:
the sources are copied into the container, built there, and only the finished
wheel plus builds/manifest.json come out. CI runs exactly this script.

Usage:
    python3 build.py                     # local build, version 0.0
    python3 build.py --version 181       # release build (CI)
    python3 build.py --no-webide         # skip the web IDE (faster, no npm)

Result:
    builds/raccoon_cli-<version>-py3-none-any.whl
    builds/manifest.json
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUILDS = ROOT / "builds"
IMAGE = "raccoon-cli-build"
VERSION_PATTERN = re.compile(r"^[0-9]+(\.[0-9]+)*$")

# Runs inside the container. /src is the repo (read-only), /out is ./builds.
# The build happens in a copy so the repo never gets build output or root-owned files.
CONTAINER_SCRIPT = r'''
set -euo pipefail
mkdir -p /tmp/work
tar -C /src \
    --exclude=./.git --exclude=./builds --exclude=./dist \
    --exclude=./web-ide/node_modules --exclude=./web-ide/dist --exclude=./web-ide/.angular \
    --exclude=./raccoon_cli/web-ide-dist --exclude=__pycache__ \
    --exclude=./build.py --exclude=./deploy.py \
    -cf - . | tar -C /tmp/work -xf -
cd /tmp/work
printf '"""Auto-generated by build.py - do not edit manually."""\n\n__version__ = "%s"\n' "$VERSION" \
    > raccoon_cli/_version.py
if [ "$WEBIDE" = "1" ]; then
    (cd web-ide && npm install && npx ng build --configuration=production)
    rm -rf raccoon_cli/web-ide-dist
    cp -r web-ide/dist/WebIDE/browser raccoon_cli/web-ide-dist
fi
python -m build --wheel --no-isolation --outdir /out .
'''


def fail(message: str) -> None:
    print(f"ERROR: {message}", file=sys.stderr)
    sys.exit(1)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description="Build the raccoon-cli wheel in Docker.")
    parser.add_argument("--version", default="0.0", help="version stamped into the wheel (default: 0.0 = local build)")
    parser.add_argument("--no-webide", action="store_true", help="do not build the web IDE")
    parser.add_argument("--image", help="use this Docker image instead of building ./Dockerfile")
    parser.add_argument(
        "--cache-dir",
        default=str(Path.home() / ".cache" / "raccoon-build" / "raccoon-cli"),
        help="npm/pip cache kept between builds (default: %(default)s)",
    )
    args = parser.parse_args()

    if not VERSION_PATTERN.match(args.version):
        fail(f"--version must be numbers separated by dots (got {args.version!r})")
    if not shutil.which("docker"):
        fail("docker not found. The build runs in a container so the host stays clean.")
    if not args.no_webide and not (ROOT / "web-ide" / "package.json").is_file():
        fail("web-ide/package.json missing. Run `git submodule update --init`, or pass --no-webide.")

    image = args.image
    if not image:
        image = IMAGE
        print(f"▶ Building Docker image {image}")
        subprocess.run(["docker", "build", "-t", image, "-f", str(ROOT / "Dockerfile"), str(ROOT)], check=True)

    BUILDS.mkdir(exist_ok=True)
    for stale in [*BUILDS.glob("raccoon_cli-*.whl"), BUILDS / "manifest.json"]:
        stale.unlink(missing_ok=True)
    cache = Path(args.cache_dir)
    (cache / "npm").mkdir(parents=True, exist_ok=True)
    (cache / "pip").mkdir(parents=True, exist_ok=True)

    import os

    print(f"▶ Building raccoon-cli {args.version}" + (" (no web IDE)" if args.no_webide else ""))
    subprocess.run(
        [
            "docker", "run", "--rm",
            "--user", f"{os.getuid()}:{os.getgid()}",
            "-e", "HOME=/tmp",
            "-e", f"VERSION={args.version}",
            "-e", f"WEBIDE={'0' if args.no_webide else '1'}",
            "-e", "npm_config_cache=/cache/npm",
            "-e", "PIP_CACHE_DIR=/cache/pip",
            "-v", f"{ROOT}:/src:ro",
            "-v", f"{BUILDS}:/out",
            "-v", f"{cache}:/cache",
            image,
            "bash", "-c", CONTAINER_SCRIPT,
        ],
        check=True,
    )

    wheels = sorted(BUILDS.glob("raccoon_cli-*.whl"))
    if len(wheels) != 1:
        fail(f"expected exactly one wheel in {BUILDS}, found {len(wheels)}")
    manifest = {
        "name": "raccoon-cli",
        "version": args.version,
        "files": [{"name": wheels[0].name, "kind": "wheel", "sha256": sha256(wheels[0])}],
    }
    (BUILDS / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"✓ {wheels[0].relative_to(ROOT)}")


if __name__ == "__main__":
    main()
